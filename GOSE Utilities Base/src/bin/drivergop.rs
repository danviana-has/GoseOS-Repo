//! `drivergop.elf` — Isolated Ring 3 GOP Linear Framebuffer Server
//!
//! Owns ONLY the GOP framebuffer MMIO capability (`fb_cap_slot`).
//! Serves text-mode console and MS-DOS TUI rendering requests over Margay IPC
//! (`ep_gop_slot`) + zero-copy SharedMemory (`shm_gop_slot` at `SHM_GOP_VA`).

#![no_std]
#![no_main]

extern crate alloc;
extern crate gose_sdk;

use core::ptr::write_volatile;

use gose_sdk::ipc_proto::{
    COLOR_BLACK, COLOR_LIGHT_GRAY, GOP_OP_CLEAR, GOP_OP_DRAW_BAR, GOP_OP_DRAW_CELL,
    GOP_OP_GET_DIMS, GOP_OP_PRINT, GOP_OP_SET_COLOR, GOP_OP_SET_MIRROR, SHM_GOP_VA,
};
use gose_sdk::libmargay::{self, GoseBootInfo};

const FB_USER_VA: u64 = 0x0000_0000_2000_0000;
const FONT_W: usize = 8;
const FONT_H: usize = 16;

struct GopState {
    active: bool,
    fb_ptr: *mut u32,
    width: usize,
    height: usize,
    pitch_pixels: usize,
    cols: usize,
    rows: usize,
    cur_col: usize,
    cur_row: usize,
    fg: u32,
    bg: u32,
    mirror_serial: bool,
}

impl GopState {
    const fn empty() -> Self {
        Self {
            active: false,
            fb_ptr: core::ptr::null_mut(),
            width: 0,
            height: 0,
            pitch_pixels: 0,
            cols: 80,
            rows: 25,
            cur_col: 0,
            cur_row: 0,
            fg: COLOR_LIGHT_GRAY,
            bg: COLOR_BLACK,
            mirror_serial: true,
        }
    }

    fn init(&mut self, bi: &GoseBootInfo) {
        if bi.fb_phys == 0 || bi.fb_width == 0 || bi.fb_height == 0 || bi.fb_bpp != 32 {
            libmargay::debug_print("[drivergop.elf] No 32bpp GOP framebuffer; serial mirror active\n");
            return;
        }
        let fb_bytes = (bi.fb_pitch as usize) * (bi.fb_height as usize);
        let num_pages = (fb_bytes + 4095) / 4096;
        if !libmargay::map_mmio(bi.fb_cap_slot, FB_USER_VA, num_pages) {
            libmargay::debug_print("[drivergop.elf] Failed to map GOP MMIO\n");
            return;
        }
        self.active = true;
        self.fb_ptr = FB_USER_VA as *mut u32;
        self.width = bi.fb_width as usize;
        self.height = bi.fb_height as usize;
        self.pitch_pixels = (bi.fb_pitch as usize) / 4;
        self.cols = self.width / FONT_W;
        self.rows = self.height / FONT_H;
        self.clear();
        libmargay::debug_print("[drivergop.elf] Isolated GOP server online\n");
    }

    fn clear(&mut self) {
        self.cur_col = 0;
        self.cur_row = 0;
        if !self.active {
            return;
        }
        for y in 0..self.height {
            let row_off = y * self.pitch_pixels;
            for x in 0..self.width {
                unsafe {
                    write_volatile(self.fb_ptr.add(row_off + x), self.bg);
                }
            }
        }
    }

    fn fill_rect(&self, x: usize, y: usize, w: usize, h: usize, color: u32) {
        if !self.active {
            return;
        }
        let max_y = (y + h).min(self.height);
        let max_x = (x + w).min(self.width);
        for py in y..max_y {
            let row_off = py * self.pitch_pixels;
            for px in x..max_x {
                unsafe {
                    write_volatile(self.fb_ptr.add(row_off + px), color);
                }
            }
        }
    }

    fn draw_char_at(&self, col: usize, row: usize, ch: u8, fg: u32, bg: u32) {
        if !self.active || col >= self.cols || row >= self.rows {
            return;
        }
        let glyph = if (0x20..=0x7E).contains(&ch) {
            FONT_8X16[(ch - 0x20) as usize]
        } else {
            FONT_8X16[0]
        };
        let px = col * FONT_W;
        let py = row * FONT_H;
        for gy in 0..FONT_H {
            let bits = glyph[gy];
            let row_off = (py + gy) * self.pitch_pixels + px;
            for gx in 0..FONT_W {
                let color = if (bits & (0x80 >> gx)) != 0 { fg } else { bg };
                unsafe {
                    write_volatile(self.fb_ptr.add(row_off + gx), color);
                }
            }
        }
    }

    fn draw_cursor(&self, col: usize, row: usize, visible: bool) {
        if !self.active || col >= self.cols || row >= self.rows {
            return;
        }
        let color = if visible { COLOR_LIGHT_GRAY } else { self.bg };
        self.fill_rect(col * FONT_W, row * FONT_H + 13, FONT_W, 3, color);
    }

    fn scroll_up(&mut self) {
        if !self.active || self.rows <= 1 {
            return;
        }
        let line_pixels = FONT_H * self.pitch_pixels;
        let copy_rows = (self.rows - 1) * FONT_H;
        unsafe {
            for y in 0..copy_rows {
                let dst = self.fb_ptr.add(y * self.pitch_pixels);
                let src = self.fb_ptr.add(y * self.pitch_pixels + line_pixels);
                core::ptr::copy(src, dst, self.width);
            }
        }
        self.fill_rect(0, (self.rows - 1) * FONT_H, self.width, FONT_H, self.bg);
        self.cur_row = self.rows - 1;
    }

    fn put_byte(&mut self, b: u8) {
        match b {
            b'\n' => {
                self.draw_cursor(self.cur_col, self.cur_row, false);
                self.cur_col = 0;
                self.cur_row += 1;
                if self.cur_row >= self.rows {
                    self.scroll_up();
                }
            }
            b'\r' => {
                self.draw_cursor(self.cur_col, self.cur_row, false);
                self.cur_col = 0;
            }
            0x08 => {
                self.draw_cursor(self.cur_col, self.cur_row, false);
                if self.cur_col > 0 {
                    self.cur_col -= 1;
                    self.draw_char_at(self.cur_col, self.cur_row, b' ', self.fg, self.bg);
                }
            }
            _ => {
                self.draw_char_at(self.cur_col, self.cur_row, b, self.fg, self.bg);
                self.cur_col += 1;
                if self.cur_col >= self.cols {
                    self.cur_col = 0;
                    self.cur_row += 1;
                    if self.cur_row >= self.rows {
                        self.scroll_up();
                    }
                }
            }
        }
        self.draw_cursor(self.cur_col, self.cur_row, true);
    }

    fn print_bytes(&mut self, data: &[u8]) {
        if self.mirror_serial {
            if let Ok(s) = core::str::from_utf8(data) {
                libmargay::debug_print(s);
            }
        }
        for &b in data {
            self.put_byte(b);
        }
    }
}

#[no_mangle]
pub extern "C" fn _start(boot_info_ptr: u64) -> ! {
    let bi = unsafe { &*(boot_info_ptr as *const GoseBootInfo) };
    let mut gop = GopState::empty();
    gop.init(bi);

    if bi.shm_gop_slot != 0 {
        let _ = libmargay::shmem_map(bi.shm_gop_slot, SHM_GOP_VA);
    }

    let ep = bi.ep_gop_slot;
    loop {
        let req = libmargay::ipc_recv(ep);
        match req.tag {
            GOP_OP_PRINT => {
                let len = (req.r0 as usize).min(4096);
                let slice = unsafe { core::slice::from_raw_parts(SHM_GOP_VA as *const u8, len) };
                gop.print_bytes(slice);
                libmargay::ipc_reply(0, 0, 0, 0, 0);
            }
            GOP_OP_CLEAR => {
                gop.clear();
                libmargay::ipc_reply(0, 0, 0, 0, 0);
            }
            GOP_OP_SET_COLOR => {
                gop.fg = req.r0 as u32;
                gop.bg = req.r1 as u32;
                libmargay::ipc_reply(0, 0, 0, 0, 0);
            }
            GOP_OP_DRAW_CELL => {
                let col = (req.r0 & 0xFFFF) as usize;
                let row = ((req.r0 >> 16) & 0xFFFF) as usize;
                gop.draw_char_at(col, row, req.r1 as u8, req.r2 as u32, req.r3 as u32);
                libmargay::ipc_reply(0, 0, 0, 0, 0);
            }
            GOP_OP_GET_DIMS => {
                libmargay::ipc_reply(0, gop.cols as u64, gop.rows as u64, 0, 0);
            }
            GOP_OP_SET_MIRROR => {
                gop.mirror_serial = req.r0 != 0;
                libmargay::ipc_reply(0, 0, 0, 0, 0);
            }
            GOP_OP_DRAW_BAR => {
                let row = req.r0 as usize;
                let len = (req.r1 as usize).min(256);
                let fg = req.r2 as u32;
                let bg = req.r3 as u32;
                let slice = unsafe { core::slice::from_raw_parts(SHM_GOP_VA as *const u8, len) };
                for col in 0..gop.cols {
                    let ch = slice.get(col).copied().unwrap_or(b' ');
                    gop.draw_char_at(col, row, ch, fg, bg);
                }
                libmargay::ipc_reply(0, 0, 0, 0, 0);
            }
            _ => {
                libmargay::ipc_reply(0, 0, 0, 0, 0);
            }
        }
    }
}

